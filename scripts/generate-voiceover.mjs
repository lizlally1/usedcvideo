#!/usr/bin/env node
/**
 * Generates public/audio/voiceover.mp3 from src/data/narration-lines.json
 * using whichever real TTS provider is configured via environment
 * variables (see .env.example). No API key is ever hard-coded here.
 *
 * Supported providers (set VOICEOVER_PROVIDER):
 *   - "elevenlabs" : ELEVENLABS_API_KEY, ELEVENLABS_VOICE_ID
 *   - "openai"     : OPENAI_API_KEY, OPENAI_TTS_VOICE
 *   - "polly"      : AWS_ACCESS_KEY_ID, AWS_SECRET_ACCESS_KEY, AWS_REGION, POLLY_VOICE_ID
 *   - "none"       : prints instructions and exits without producing audio
 *
 * Each line is synthesized as a SEPARATE API call and then placed
 * sequentially (previous line's end + a fixed pause), using ffprobe to
 * measure each line's actual rendered duration. This is deliberate, not
 * just for pacing: it's what makes lines never overlap/talk over each
 * other regardless of how fast or slow the provider's voice happens to
 * speak, and it's what lets the on-screen captions
 * (src/data/narration-timing.json → src/data/content.ts CAPTIONS) stay
 * exactly in sync with the real audio.
 *
 * Usage:
 *   cp .env.example .env   # then fill in one provider's keys
 *   npm run voiceover
 *
 * If you have no API key available, either:
 *   1) run `npm run voiceover:fallback` for an offline placeholder voice, or
 *   2) manually drop a finished narration file at public/audio/voiceover.mp3
 *      and hand-author src/data/narration-timing.json to match it.
 */

import {execSync} from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const LINES_PATH = path.join(ROOT, 'src', 'data', 'narration-lines.json');
const TIMING_OUTPUT_PATH = path.join(ROOT, 'src', 'data', 'narration-timing.json');
const AUDIO_OUTPUT_PATH = path.join(ROOT, 'public', 'audio', 'voiceover.mp3');
const TIMESTAMPS_TXT_PATH = path.join(ROOT, 'voiceover-timestamps.txt');

const TOTAL_DURATION_SECONDS = 151;
const LEAD_IN_SECONDS = 3.0;
const GAP_SECONDS = 0.65;

function loadEnvFile() {
  const envPath = path.join(ROOT, '.env');
  if (!fs.existsSync(envPath)) return;
  const lines = fs.readFileSync(envPath, 'utf-8').split('\n');
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    const value = trimmed.slice(eq + 1).trim();
    if (!(key in process.env)) process.env[key] = value;
  }
}

function ffprobeDuration(file) {
  const out = execSync(
    `ffprobe -v error -show_entries format=duration -of default=noprint_wrappers=1:nokey=1 "${file}"`,
  ).toString();
  return parseFloat(out);
}

function round2(n) {
  return Math.round(n * 100) / 100;
}

function fmtTime(seconds) {
  const m = Math.floor(seconds / 60);
  const s = (seconds % 60).toFixed(2).padStart(5, '0');
  return `${String(m).padStart(2, '0')}:${s}`;
}

function renderTimestampsTxt(timing, providerLabel) {
  const header = `U.S. ENERGY DEVELOPMENT CORPORATION — VOICEOVER TIMESTAMPS
Auto-generated by scripts/generate-voiceover.mjs (provider: ${providerLabel})
from the ACTUAL synthesized audio — every line's start/end below is the
real timing baked into public/audio/voiceover.mp3. src/data/content.ts
imports src/data/narration-timing.json for the on-screen CAPTIONS track,
so it always matches this file.

`;
  const body = timing.map((t) => `[${fmtTime(t.start)} - ${fmtTime(t.end)}]  ${t.text}`).join('\n\n');
  return header + body + '\n';
}

async function main() {
  loadEnvFile();
  const provider = (process.env.VOICEOVER_PROVIDER || 'none').toLowerCase();
  const lines = JSON.parse(fs.readFileSync(LINES_PATH, 'utf-8'));

  if (provider === 'none') {
    console.log(`
No VOICEOVER_PROVIDER configured (.env has VOICEOVER_PROVIDER=none or is missing).

This project supports ElevenLabs, OpenAI TTS, and Amazon Polly. To generate the
final narration:
  1. cp .env.example .env
  2. Set VOICEOVER_PROVIDER to "elevenlabs", "openai", or "polly"
  3. Fill in that provider's credentials in .env
  4. Re-run: npm run voiceover

In the meantime, you can:
  - Run "npm run voiceover:fallback" for an offline placeholder voice
    (RHVoice), or
  - Manually place a finished narration file at public/audio/voiceover.mp3
`);
    process.exit(0);
  }

  const synthesizers = {elevenlabs: synthElevenLabs, openai: synthOpenAI, polly: synthPolly};
  const synth = synthesizers[provider];
  if (!synth) {
    console.error(`Unknown VOICEOVER_PROVIDER "${provider}". Use elevenlabs | openai | polly | none.`);
    process.exit(1);
  }

  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'usedc-vo-'));
  let cursor = LEAD_IN_SECONDS;
  const timing = [];
  const audioFiles = [];

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const filePath = path.join(tmpDir, `line-${i}.mp3`);
    console.log(`Synthesizing line ${i + 1}/${lines.length} via ${provider}...`);
    await synth(line.text, filePath);

    const duration = ffprobeDuration(filePath);
    const start = cursor;
    const end = start + duration;
    timing.push({start: round2(start), end: round2(end), text: line.text});
    audioFiles.push(filePath);
    cursor = end + GAP_SECONDS;
  }

  const finalEnd = timing[timing.length - 1].end;
  if (finalEnd > TOTAL_DURATION_SECONDS - 1) {
    console.error(
      `Narration (ends at ${finalEnd.toFixed(1)}s) doesn't fit inside the ${TOTAL_DURATION_SECONDS}s video with a 1s safety margin. Shorten the script or lengthen the video.`,
    );
    process.exit(1);
  }

  const inputs = audioFiles.map((f) => `-i "${f}"`).join(' ');
  const delayFilters = timing
    .map((t, i) => `[${i}:a]adelay=${Math.round(t.start * 1000)}|${Math.round(t.start * 1000)}[a${i}]`)
    .join(';');
  const mixInputs = timing.map((_, i) => `[a${i}]`).join('');
  const filterComplex = `${delayFilters};${mixInputs}amix=inputs=${timing.length}:normalize=0,loudnorm=I=-16:TP=-1.5:LRA=11,apad=whole_dur=${TOTAL_DURATION_SECONDS}[out]`;

  fs.mkdirSync(path.dirname(AUDIO_OUTPUT_PATH), {recursive: true});
  execSync(
    `ffmpeg -y ${inputs} -filter_complex "${filterComplex}" -map "[out]" -t ${TOTAL_DURATION_SECONDS} -ar 44100 -b:a 192k "${AUDIO_OUTPUT_PATH}"`,
    {stdio: ['ignore', 'pipe', 'inherit']},
  );

  fs.writeFileSync(TIMING_OUTPUT_PATH, JSON.stringify(timing, null, 2) + '\n');
  fs.writeFileSync(TIMESTAMPS_TXT_PATH, renderTimestampsTxt(timing, provider));
  fs.rmSync(tmpDir, {recursive: true, force: true});

  console.log(`Wrote ${AUDIO_OUTPUT_PATH} via ${provider} (ends at ${finalEnd.toFixed(1)}s, no overlaps).`);
  console.log(`Wrote ${TIMING_OUTPUT_PATH} and ${TIMESTAMPS_TXT_PATH}.`);
}

async function synthElevenLabs(text, outPath) {
  const apiKey = process.env.ELEVENLABS_API_KEY;
  const voiceId = process.env.ELEVENLABS_VOICE_ID;
  if (!apiKey || !voiceId) {
    console.error('Missing ELEVENLABS_API_KEY or ELEVENLABS_VOICE_ID in .env');
    process.exit(1);
  }
  const res = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${voiceId}`, {
    method: 'POST',
    headers: {'xi-api-key': apiKey, 'Content-Type': 'application/json', accept: 'audio/mpeg'},
    body: JSON.stringify({
      text,
      model_id: 'eleven_multilingual_v2',
      voice_settings: {stability: 0.45, similarity_boost: 0.75},
    }),
  });
  if (!res.ok) {
    console.error(`ElevenLabs error: ${res.status} ${await res.text()}`);
    process.exit(1);
  }
  fs.writeFileSync(outPath, Buffer.from(await res.arrayBuffer()));
}

async function synthOpenAI(text, outPath) {
  const apiKey = process.env.OPENAI_API_KEY;
  const voice = process.env.OPENAI_TTS_VOICE || 'onyx';
  if (!apiKey) {
    console.error('Missing OPENAI_API_KEY in .env');
    process.exit(1);
  }
  const res = await fetch('https://api.openai.com/v1/audio/speech', {
    method: 'POST',
    headers: {Authorization: `Bearer ${apiKey}`, 'Content-Type': 'application/json'},
    body: JSON.stringify({model: 'gpt-4o-mini-tts', voice, input: text, format: 'mp3'}),
  });
  if (!res.ok) {
    console.error(`OpenAI TTS error: ${res.status} ${await res.text()}`);
    process.exit(1);
  }
  fs.writeFileSync(outPath, Buffer.from(await res.arrayBuffer()));
}

async function synthPolly(text, outPath) {
  let PollyClient, SynthesizeSpeechCommand;
  try {
    ({PollyClient, SynthesizeSpeechCommand} = await import('@aws-sdk/client-polly'));
  } catch {
    console.error('Amazon Polly requires the AWS SDK. Install it first:\n  npm install @aws-sdk/client-polly');
    process.exit(1);
  }
  const client = new PollyClient({region: process.env.AWS_REGION || 'us-east-1'});
  const command = new SynthesizeSpeechCommand({
    Text: text,
    OutputFormat: 'mp3',
    VoiceId: process.env.POLLY_VOICE_ID || 'Matthew',
    Engine: 'neural',
  });
  const response = await client.send(command);
  const chunks = [];
  for await (const chunk of response.AudioStream) chunks.push(chunk);
  fs.writeFileSync(outPath, Buffer.concat(chunks));
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
